import os
from dotenv import load_dotenv
from langchain_openai import ChatOpenAI
from langchain_core.messages import SystemMessage, HumanMessage

load_dotenv()

class LLMService:
    def __init__(self):
        self.api_key = os.getenv("OPENAI_API_KEY", "").strip()
        self.model_name = os.getenv("OPENAI_MODEL", "gpt-3.5-turbo")
        self.base_url = os.getenv("OPENAI_BASE_URL", None)
        
    def generate_response(self, user_message: str, system_instruction: str = None) -> str:
        """
        Generate a text response using LangChain ChatOpenAI LLM API.
        
        :param user_message: The prompt/question from the user.
        :param system_instruction: Optional system instruction guiding LLM behavior.
        :return: String response generated by the LLM.
        """
        if not self.api_key or self.api_key == "your_openai_api_key_here":
            raise ValueError(
                "OPENAI_API_KEY is missing or unconfigured in backend/.env file. "
                "Please add a valid API key to backend/.env."
            )

        default_system_instruction = (
            "You are a helpful, professional AI coding assistant. "
            "Provide concise, accurate, and structured answers to software engineering questions."
        )
        
        system_text = system_instruction if system_instruction else default_system_instruction

        # Initialize LangChain ChatOpenAI Model
        # temperature=0.2 ensures focused, non-hallucinatory outputs
        kwargs = {
            "model_name": self.model_name,
            "openai_api_key": self.api_key,
            "temperature": 0.2,
        }
        if self.base_url and self.base_url.strip():
            kwargs["openai_api_base"] = self.base_url.strip()

        llm = ChatOpenAI(**kwargs)

        # Construct messages list using LangChain message primitives
        messages = [
            SystemMessage(content=system_text),
            HumanMessage(content=user_message)
        ]

        # Call the LLM API via LangChain
        response = llm.invoke(messages)
        return response.content

# Singleton instance for easy import across backend endpoints
llm_service = LLMService()
